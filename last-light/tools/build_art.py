"""Copies the loadable art from the unpacked art bundle into last-light/art/
and writes last-light/art/manifest.js (one LL_ART global).

Usage: python3 -I build_art.py <unpacked last_light_art dir> <last-light dir>

Rules (from the bundle README / sprite-art-spec):
- load *_strip.png, never *_strip_user*.png
- plain name.png only where no strip exists (floors, terrain, fx singles, icons, hub, title)
- _build_scripts/ and reference/ are not shipped; appicon/ is shipped for packaging
  but is not listed in the manifest (the game never loads it).
"""
import json, os, shutil, sys
from PIL import Image

src, dst = sys.argv[1], sys.argv[2]
art = os.path.join(dst, 'art')
if os.path.isdir(art):
    shutil.rmtree(art)
os.makedirs(art)

FOLDERS = ['units', 'enemies', 'floors', 'terrain', 'fx', 'icons', 'hub', 'title']
sprites = {}
for folder in FOLDERS:
    fdir = os.path.join(src, folder)
    names = sorted(os.listdir(fdir))
    stems_with_strip = {n[:-len('_strip.png')] for n in names if n.endswith('_strip.png')}
    os.makedirs(os.path.join(art, folder))
    for n in names:
        p = os.path.join(fdir, n)
        if not n.endswith('.png') or not os.path.isfile(p):
            continue
        if '_strip_user' in n or n.endswith('_user.png') or n.startswith('ui_') and n.endswith('_strip_user.png'):
            continue
        stem = n[:-4]
        if n.endswith('_strip.png'):
            key = stem[:-len('_strip')]
        else:
            if stem in stems_with_strip:
                # frame-0 preview of a strip: ship it (portraits use it later) under a _f0 key
                key = stem + '_f0'
            else:
                key = stem
        shutil.copy2(p, os.path.join(art, folder, n))
        w, h = Image.open(p).size
        fw = 24 if folder in ('units', 'enemies', 'floors', 'terrain', 'fx') and h == 24 else w
        sprites[key] = {'src': f'art/{folder}/{n}', 'w': w, 'h': h, 'fw': fw, 'frames': max(1, w // fw)}
    for man in [n for n in names if n.endswith('_manifest.json')]:
        shutil.copy2(os.path.join(fdir, man), os.path.join(art, folder, man))

# appicon: shipped for packaging only
shutil.copytree(os.path.join(src, 'appicon'), os.path.join(art, 'appicon'),
                ignore=shutil.ignore_patterns('_build_scripts', '*_user.png'))

def load(folder, name):
    with open(os.path.join(src, folder, name)) as f:
        return json.load(f)

LL_ART = {
    'version': '2026-10-22',
    'sprites': sprites,
    'enemyAnim': load('enemies', 'enemy_anim_manifest.json'),
    'fx': load('fx', 'fx_manifest.json'),
    'icons': load('icons', 'icons_manifest.json'),
    'hub': load('hub', 'hub_manifest.json'),
}
with open(os.path.join(art, 'manifest.js'), 'w') as f:
    f.write('/* Generated by build_art.py from last_light_art.zip -- do not edit by hand. */\n')
    f.write('window.LL_ART = ')
    json.dump(LL_ART, f, separators=(',', ':'))
    f.write(';\n')
# v2.2.4: the page icons (favicon, Apple touch icon, web-app manifest icons) are made
# from the official app icon, since this script clears art/ on every run.
web = os.path.join(art, 'appicon', 'web')
os.makedirs(web, exist_ok=True)
big = Image.open(os.path.join(art, 'appicon', 'appicon_ios_1024.png')).convert('RGB')
for n in (180, 192, 512):
    big.resize((n, n), Image.LANCZOS).save(os.path.join(web, 'icon_%d.png' % n), optimize=True)
Image.open(os.path.join(art, 'appicon', 'appicon_source_64.png')).convert('RGBA') \
    .resize((32, 32), Image.BOX).save(os.path.join(web, 'favicon_32.png'), optimize=True)
print(len(sprites), 'sprites listed')
